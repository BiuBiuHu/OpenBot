function applyWords(text: string, pairs: [string, string][]): string {
  let out = text;
  const ranked = [...pairs].sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of ranked) {
    if (from && out.includes(from)) out = out.split(from).join(to);
  }
  return out;
}

function charMap(pairs: [string, string][]): Map<string, string> {
  const map = new Map<string, string>();
  for (const [from, to] of pairs) {
    if (from && to && from !== to) map.set(from, to);
  }
  return map;
}

const SIMP_CHAR_MAP = charMap(TO_SIMP_CHARS);
const TRAD_CHAR_MAP = charMap(TO_SIMP_CHARS.map(([a, b]) => [b, a]));

function applyChars(text: string, map: Map<string, string>): string {
  return Array.from(text, (ch) => map.get(ch) ?? ch).join("");
}

export function toSimplified(text: string): string {
  return applyChars(applyWords(String(text || ""), TO_SIMP_WORDS), SIMP_CHAR_MAP);
}

export function toTraditional(text: string): string {
  const reversed = TO_SIMP_WORDS.map(([a, b]) => [b, a] as [string, string]);
  return applyChars(applyWords(String(text || ""), reversed), TRAD_CHAR_MAP);
}

export function normalizeChatLanguage(value?: string | null): ChatLanguage {
  const v = String(value || "").trim();
  if (v === "zh-TW" || v === "zh-Hant" || v === "zh-HK" || v === "zh-Hant-TW") return "zh-TW";
  if (v === "en" || v === "en-US" || v === "en-GB" || v === "english") return "en";
  if (v === "zh-CN" || v === "zh" || v === "zh-Hans" || v === "zh-Hans-CN" || v === "zh-SG") return "zh-CN";
  return DEFAULT_CHAT_LANGUAGE;
}

export function prefersChineseSearch(language: ChatLanguage): boolean {
  return language === "zh-CN" || language === "zh-TW";
}

export function applyChatLanguage(text: string, language?: string | null): string {
  const lang = normalizeChatLanguage(language);
  const raw = String(text || "");
  if (lang === "zh-TW") return toTraditional(raw);
  if (lang === "zh-CN") return toSimplified(raw);
  return raw;
}
